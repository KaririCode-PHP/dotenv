<?php

declare(strict_types=1);

namespace KaririCode\Dotenv\Cache;

use KaririCode\Dotenv\Exception\CacheException;

/**
 * OPcache-friendly cache: a PHP file that returns an array.
 *
 * OPcache compiles the file once; later requests read it from shared
 * memory with no .env parsing. A cache is only returned by load() when
 * every recorded source file still has the same path, mtime, size and
 * inode — including files that were absent when the cache was written,
 * so creating a new `.env.local` invalidates it too.
 *
 * Standalone — no framework or external cache server required.
 *
 * Preconditions: the cache directory exists and is writable for dump(); the
 * file is written only by dump(), never by hand.
 *
 * Thread-safety: stateless; one instance serves every caller.
 *
 * Side effects: dump() writes a temporary file, renames it over the cache
 * and invalidates the OPcache entry; clear() deletes the file; load()
 * includes the file; computeSourceHash() stats the sources.
 *
 * Example:
 *
 *     $cache = new PhpFileCache();
 *     $cache->dump($path, $snapshot);
 *     $snapshot = $cache->load($path); // null when a source changed since
 *
 * References: ADR-005, SPEC-001. ARFA 1.3 P5: the source fingerprint is
 * observable.
 *
 * @since   4.2.0
 */
final readonly class PhpFileCache
{
    private const int FORMAT = 2;

    /**
     * Writes the snapshot atomically (temporary file + rename).
     *
     * @throws CacheException When the file cannot be written or moved into place.
     */
    public function dump(string $path, CacheSnapshot $snapshot): void
    {
        $payload = [
            'meta' => [
                'format' => self::FORMAT,
                'generator' => 'KaririCode\\Dotenv',
                'generated_at' => date('c'),
                'strategy' => $snapshot->strategy,
                'environment' => $snapshot->environment,
                'requested_environment' => $snapshot->requestedEnvironment,
                'encrypted' => $snapshot->encrypted,
                'sources' => $snapshot->sources,
                'source_hash' => $this->computeSourceHash($snapshot->sources),
            ],
            'variables' => $snapshot->variables,
        ];

        $content = "<?php\n\n"
            . "// Auto-generated by KaririCode\\Dotenv — do not edit manually.\n"
            . "// Regenerate with: vendor/bin/kariricode-dotenv cache:dump\n\n"
            . 'return ' . var_export($payload, true) . ";\n";

        $tmpFile = $path . '.tmp.' . bin2hex(random_bytes(6));

        if (!$this->quietly(static fn(): bool => file_put_contents($tmpFile, $content) !== false)) {
            throw CacheException::writeFailed($path);
        }

        if (!$this->quietly(static fn(): bool => rename($tmpFile, $path))) {
            if (is_file($tmpFile)) {
                unlink($tmpFile);
            }

            throw CacheException::writeFailed($path);
        }

        if (function_exists('opcache_invalidate')) {
            opcache_invalidate($path, true);
        }
    }

    /**
     * Returns the cached snapshot, or null when the file is missing,
     * malformed, from another format version, or stale.
     */
    public function load(string $path): ?CacheSnapshot
    {
        if (!is_file($path) || !is_readable($path)) {
            return null;
        }

        $data = include $path;
        $meta = is_array($data) ? $data['meta'] ?? null : null;

        if (!is_array($data) || !is_array($meta) || ($meta['format'] ?? null) !== self::FORMAT) {
            return null;
        }

        return $this->snapshot($meta, $data['variables'] ?? null);
    }

    public function clear(string $path): void
    {
        if (!is_file($path)) {
            return;
        }

        unlink($path);

        if (function_exists('opcache_invalidate')) {
            opcache_invalidate($path, true);
        }
    }

    /**
     * Fingerprint of the files' metadata (path, mtime, size, inode, or
     * "absent"). Reads no file contents.
     *
     * @param list<string> $filePaths
     */
    public function computeSourceHash(array $filePaths): string
    {
        $context = hash_init('sha256');

        foreach ($filePaths as $filePath) {
            clearstatcache(true, $filePath);
            hash_update($context, $filePath . "\0");
            $stat = is_file($filePath) ? stat($filePath) : false;
            hash_update($context, $stat === false ? 'absent' : $stat['mtime'] . ':' . $stat['size'] . ':' . $stat['ino']);
            hash_update($context, "\n");
        }

        return hash_final($context);
    }

    /**
     * The snapshot a cache file's metadata and variables describe, or null
     * when a field is missing or mistyped, or a source changed since.
     *
     * @param array<array-key, mixed> $meta
     */
    private function snapshot(array $meta, mixed $variables): ?CacheSnapshot
    {
        $sources = $this->stringList($meta['sources'] ?? null);
        $map = $this->stringMap($variables);

        if ($sources === null || $map === null || !$this->isFresh($meta['source_hash'] ?? null, $sources)) {
            return null;
        }

        return $this->describe(meta: $meta, sources: $sources, variables: $map);
    }

    /**
     * @param array<array-key, mixed> $meta
     * @param list<string> $sources
     * @param array<string, string> $variables
     */
    private function describe(array $meta, array $sources, array $variables): ?CacheSnapshot
    {
        $strategy = $meta['strategy'] ?? null;
        $encrypted = $meta['encrypted'] ?? null;
        $environment = $meta['environment'] ?? null;
        $requested = $meta['requested_environment'] ?? null;

        if (!is_string($strategy) || !is_bool($encrypted)
            || !$this->isNullableString($environment) || !$this->isNullableString($requested)
        ) {
            return null;
        }

        return new CacheSnapshot(
            strategy: $strategy,
            environment: $environment,
            requestedEnvironment: $requested,
            sources: $sources,
            variables: $variables,
            encrypted: $encrypted,
        );
    }

    /**
     * Runs a filesystem call with PHP's warnings silenced, so its failure
     * reaches the caller as a CacheException and never as a warning.
     *
     * @param \Closure(): bool $operation
     */
    private function quietly(\Closure $operation): bool
    {
        set_error_handler(static fn(): bool => true);

        try {
            return $operation();
        } finally {
            restore_error_handler();
        }
    }

    /** @param list<string> $sources */
    private function isFresh(mixed $hash, array $sources): bool
    {
        return is_string($hash) && hash_equals($hash, $this->computeSourceHash($sources));
    }

    /** @psalm-assert-if-true string|null $value */
    private function isNullableString(mixed $value): bool
    {
        return $value === null || is_string($value);
    }

    /**
     * @return list<string>|null
     */
    private function stringList(mixed $value): ?array
    {
        if (!is_array($value) || !array_is_list($value)) {
            return null;
        }

        $result = [];

        foreach ($value as $item) {
            if (!is_string($item)) {
                return null;
            }

            $result[] = $item;
        }

        return $result;
    }

    /**
     * @return array<string, string>|null
     */
    private function stringMap(mixed $value): ?array
    {
        if (!is_array($value)) {
            return null;
        }

        $result = [];

        foreach ($value as $key => $item) {
            if (!is_string($key) || !is_string($item)) {
                return null;
            }

            $result[$key] = $item;
        }

        return $result;
    }
}
