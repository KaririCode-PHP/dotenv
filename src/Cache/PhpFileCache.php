<?php

declare(strict_types=1);

namespace KaririCode\Dotenv\Cache;

use KaririCode\Dotenv\Exception\CacheException;

/**
 * OPcache-friendly cache: a PHP file that returns an array.
 *
 * OPcache compiles the file once; later requests read it from shared
 * memory with no .env parsing. A cache is only returned by load() when
 * every recorded source file still has the same path, mtime, size and
 * inode — including files that were absent when the cache was written,
 * so creating a new `.env.local` invalidates it too.
 *
 * Standalone — no framework or external cache server required.
 *
 * @package KaririCode\Dotenv
 * @since   4.2.0
 */
final readonly class PhpFileCache
{
    private const int FORMAT = 2;

    /**
     * Writes the snapshot atomically (temporary file + rename).
     *
     * @throws CacheException When the file cannot be written or moved into place.
     */
    public function dump(string $path, CacheSnapshot $snapshot): void
    {
        $payload = [
            'meta' => [
                'format' => self::FORMAT,
                'generator' => 'KaririCode\\Dotenv',
                'generated_at' => date('c'),
                'strategy' => $snapshot->strategy,
                'environment' => $snapshot->environment,
                'requested_environment' => $snapshot->requestedEnvironment,
                'encrypted' => $snapshot->encrypted,
                'sources' => $snapshot->sources,
                'source_hash' => $this->computeSourceHash($snapshot->sources),
            ],
            'variables' => $snapshot->variables,
        ];

        $content = "<?php\n\n"
            . "// Auto-generated by KaririCode\\Dotenv — do not edit manually.\n"
            . "// Regenerate with: vendor/bin/kariricode-dotenv cache:dump\n\n"
            . 'return ' . var_export($payload, true) . ";\n";

        $tmpFile = $path . '.tmp.' . bin2hex(random_bytes(6));

        if (file_put_contents($tmpFile, $content) === false) {
            throw CacheException::writeFailed($path);
        }

        if (!rename($tmpFile, $path)) {
            if (is_file($tmpFile)) {
                unlink($tmpFile);
            }

            throw CacheException::writeFailed($path);
        }

        if (function_exists('opcache_invalidate')) {
            opcache_invalidate($path, true);
        }
    }

    /**
     * Returns the cached snapshot, or null when the file is missing,
     * malformed, from another format version, or stale.
     */
    public function load(string $path): ?CacheSnapshot
    {
        if (!is_file($path) || !is_readable($path)) {
            return null;
        }

        $data = include $path;

        if (!is_array($data) || !is_array($data['meta'] ?? null) || !is_array($data['variables'] ?? null)) {
            return null;
        }

        $meta = $data['meta'];

        if (($meta['format'] ?? null) !== self::FORMAT
            || !is_string($meta['strategy'] ?? null)
            || !is_string($meta['source_hash'] ?? null)
            || !is_bool($meta['encrypted'] ?? null)
            || !$this->isNullableString($meta['environment'] ?? null)
            || !$this->isNullableString($meta['requested_environment'] ?? null)
        ) {
            return null;
        }

        $sources = $this->stringList($meta['sources'] ?? null);
        $variables = $this->stringMap($data['variables']);

        if ($sources === null || $variables === null) {
            return null;
        }

        if (!hash_equals($meta['source_hash'], $this->computeSourceHash($sources))) {
            return null;
        }

        /** @var string|null $environment */
        $environment = $meta['environment'] ?? null;
        /** @var string|null $requested */
        $requested = $meta['requested_environment'] ?? null;

        return new CacheSnapshot($meta['strategy'], $environment, $requested, $sources, $variables, $meta['encrypted']);
    }

    public function clear(string $path): void
    {
        if (!is_file($path)) {
            return;
        }

        unlink($path);

        if (function_exists('opcache_invalidate')) {
            opcache_invalidate($path, true);
        }
    }

    /**
     * Fingerprint of the files' metadata (path, mtime, size, inode, or
     * "absent"). Reads no file contents.
     *
     * @param list<string> $filePaths
     */
    public function computeSourceHash(array $filePaths): string
    {
        $context = hash_init('sha256');

        foreach ($filePaths as $filePath) {
            clearstatcache(true, $filePath);
            hash_update($context, $filePath . "\0");
            hash_update(
                $context,
                is_file($filePath)
                    ? filemtime($filePath) . ':' . filesize($filePath) . ':' . fileinode($filePath)
                    : 'absent',
            );
            hash_update($context, "\n");
        }

        return hash_final($context);
    }

    private function isNullableString(mixed $value): bool
    {
        return $value === null || is_string($value);
    }

    /**
     * @return list<string>|null
     */
    private function stringList(mixed $value): ?array
    {
        if (!is_array($value) || !array_is_list($value)) {
            return null;
        }

        $result = [];

        foreach ($value as $item) {
            if (!is_string($item)) {
                return null;
            }

            $result[] = $item;
        }

        return $result;
    }

    /**
     * @param array<mixed> $value
     *
     * @return array<string, string>|null
     */
    private function stringMap(array $value): ?array
    {
        $result = [];

        foreach ($value as $key => $item) {
            if (!is_string($key) || !is_string($item)) {
                return null;
            }

            $result[$key] = $item;
        }

        return $result;
    }
}
